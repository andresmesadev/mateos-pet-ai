// Authenticated browser checks using the in-memory fixture only.
const assert = require('node:assert/strict');
const path = require('node:path');

module.exports = async function verify({ login, origin, errors, directory, calls, control }) {
  const { context, page } = await login('admin', 320);
  const releases = [];
  const url = route => origin + '/dashboard/' + route + (route.includes('?') ? '&' : '?') + 'tenant=fixture-selected';
  const writes = suffix => calls.filter(call => call.method !== 'GET' && call.path.endsWith(suffix));
  const focused = id => page.waitForFunction(id => document.activeElement?.id === id, id);
  const activeDialog = () => page.getByRole('dialog').last();
  const saveAppointment = () => activeDialog().getByRole('button', { name: 'Crear cita', exact: true }).click();
  const saveProduct = () => activeDialog().getByRole('button', { name: /Guardar producto|Guardar cambios/, exact: true }).click();
  async function fixedFooter(label, width) {
    const dialog = activeDialog();
    assert.equal(await dialog.locator('[data-form-body]').count(), 1);
    const footer = dialog.locator('[data-slot="dialog-footer"]');
    const initial = await footer.boundingBox();
    await dialog.locator('[data-form-body]').evaluate(body => { body.scrollTop = body.scrollHeight; });
    const final = await footer.boundingBox();
    assert(Math.abs(initial.y - final.y) < 1, 'Footer must stay fixed when body scrolls');
    assert(final.y >= 0 && final.y + final.height <= 609, 'Footer must stay inside viewport');
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    const clipped = await dialog.locator('button').evaluateAll(buttons => buttons.filter(button => {
      const r = button.getBoundingClientRect(); return r.width && r.height && (r.left < -1 || r.right > innerWidth + 1);
    }).map(button => button.textContent));
    assert.deepEqual(clipped, [], 'Actions must fit horizontally');
    await page.screenshot({ path: path.join(directory, `forms-${label}-${width}.png`), fullPage: true });
  }
  async function cancel() {
    await activeDialog().getByRole('button', { name: 'Cancelar', exact: true }).click();
    if (await page.getByRole('alertdialog').isVisible()) await page.getByRole('button', { name: 'Descartar cambios', exact: true }).click();
  }
  try {
    for (const width of [320, 768, 1440]) {
      await page.setViewportSize({width,height:608});
      await page.goto(url('contacto'),{waitUntil:'networkidle'});
      await page.getByRole('button',{name:'Nuevo cliente',exact:true}).click();
      assert.deepEqual(await activeDialog().locator('legend').allTextContents(),['Contacto del propietario','Mascota']);
      assert.equal(await activeDialog().locator('details').getAttribute('open'),null);
      await page.locator('#op-name').fill('Borrador de prueba');
      await page.getByRole('button',{name:'Agregar otra mascota'}).click();
      await fixedFooter('registration',width);
      await cancel();
      console.log(`PASS: ${width}px owner/pets sections, optional details collapsed, long registration scroll with fixed footer and discard guard.`);
      await page.goto(url('calendar?new=1'), {waitUntil:'networkidle'});
      const before = writes('/appointments').length;
      await saveAppointment(); await focused('appointment-client');
      await page.locator('#appointment-client').fill('Ana');
      await saveAppointment(); await focused('appointment-client');
      await page.getByRole('button', { name: /Ana Prueba/ }).first().click();
      await saveAppointment(); await focused('appointment-pet');
      await page.locator('#appointment-pet').selectOption('pet-existing');
      await saveAppointment(); await focused('appointment-service');
      await page.locator('#appointment-service').selectOption('service-vet');
      await page.locator('#appointment-hour option[value="9.5"]').waitFor({state:'attached'});
      await saveAppointment(); await focused('appointment-hour');
      assert.equal(writes('/appointments').length, before);
      await page.locator('#appointment-professional').selectOption('vet');
      await page.locator('#appointment-hour option[value="9.5"]').waitFor({state:'attached'});
      await page.locator('#appointment-hour').selectOption('9.5');
      await fixedFooter('appointment', width);
      control.appointment(409); await saveAppointment();
      await activeDialog().getByRole('alert').filter({hasText:'turno acaba'}).waitFor();
      assert.equal(await page.locator('#appointment-hour').inputValue(), '');
      assert.equal(await page.locator('#appointment-pet').inputValue(), 'pet-existing');
      assert.equal(await page.locator('#appointment-service').inputValue(), 'service-vet');
      await page.locator('#appointment-hour option[value="10"]').waitFor({state:'attached'});
      await page.locator('#appointment-hour').selectOption('10');
      control.appointment(503); await saveAppointment();
      await activeDialog().getByRole('alert').filter({hasText:'cita de prueba'}).waitFor();
      assert.equal(await page.locator('#appointment-hour').inputValue(), '10');
      control.appointment(0); await saveAppointment();
      await page.locator('#appointment-client').waitFor({state:'hidden'});
      assert.equal(writes('/appointments').length, before + 3);
      const request = writes('/appointments').at(-1);
      assert.deepEqual(Object.keys(request.body).sort(), ['dateKey','hour','petId','serviceId','staffId','userId']);
      assert.equal(request.body.hour,10); assert.equal(request.body.userId,'owner-existing');
      console.log(`PASS: ${width}px appointment field focus, typed client selection, 409 refresh, retained failure and save; fixed footer.`);

      await page.goto(url('contacto'), {waitUntil:'networkidle'});
      const edit = page.locator('button').filter({hasText:/^Editar$/}).first();
      if (width < 768) await edit.click(); else await page.locator('button[title="Editar cliente"]').first().click();
      await page.locator('#edit-client-phone').waitFor();
      const beforeClient = calls.filter(c => c.method === 'PATCH' && /\/clients\//.test(c.path)).length;
      await page.locator('#edit-client-phone').fill('');
      await activeDialog().getByRole('button',{name:'Guardar cambios',exact:true}).click(); await focused('edit-client-phone');
      await page.locator('#edit-client-phone').fill('0000000001');
      await page.locator('#edit-client-form summary').click();
      await page.locator('#edit-client-email').fill('incorrecto');
      await page.locator('#edit-client-form summary').click();
      await activeDialog().getByRole('button',{name:'Guardar cambios',exact:true}).click(); await focused('edit-client-email');
      assert.equal(await page.locator('#edit-client-form details').getAttribute('open'),'');
      assert.equal(calls.filter(c => c.method === 'PATCH' && /\/clients\//.test(c.path)).length,beforeClient);
      await page.locator('#edit-client-email').fill('contacto@fixture.invalid');
      await page.locator('#edit-client-name').fill('Ana Prueba');
      await page.locator('#edit-client-address').fill('Dirección de prueba ' + width);
      await fixedFooter('client',width);
      control.client(true);
      await activeDialog().getByRole('button',{name:'Guardar cambios',exact:true}).click();
      await activeDialog().getByRole('alert').filter({hasText:'cliente de prueba'}).waitFor();
      assert.equal(await page.locator('#edit-client-email').inputValue(),'contacto@fixture.invalid');
      await activeDialog().getByRole('button',{name:'Cancelar',exact:true}).click();
      await page.getByRole('alertdialog').waitFor();
      await page.getByRole('button',{name:'Seguir editando',exact:true}).click();
      control.client(false);
      await activeDialog().getByRole('button',{name:'Guardar cambios',exact:true}).click();
      await page.locator('#edit-client-phone').waitFor({state:'hidden'});
      await activeDialog().getByRole('button',{name:'Cerrar',exact:true}).click();
      console.log(`PASS: ${width}px client phone/email validation, optional section opens on error, retained save failure, discard guard and retry; fixed footer.`);

      await page.goto(url('inventory'),{waitUntil:'networkidle'});
      await page.getByRole('button',{name:'Nuevo producto',exact:true}).click();
      const beforeProduct = writes('/inventory/products').length;
      await saveProduct(); await focused('product-name');
      await page.locator('#product-name').fill('Champú Prueba');
      await page.locator('#product-internalCode').fill('TEST-' + width);
      await page.locator('#product-category').fill('Aseo');
      await page.locator('#product-presentation').fill('Frasco de 250 ml');
      await page.locator('#product-referenceCost').fill('12000');
      await saveProduct(); await focused('product-uses');
      await page.locator('#product-use-retail').check();
      await page.locator('#product-referenceCost').fill('12.000');
      await page.locator('#product-salePrice').fill('18000');
      await saveProduct(); await focused('product-referenceCost');
      await page.locator('#product-referenceCost').fill('12000,50');
      await page.locator('#product-salePrice').fill('0');
      await saveProduct(); await focused('product-salePrice');
      await page.locator('#product-salePrice').fill('18000');
      await page.locator('#product-stockMinimum').fill('1.5');
      await saveProduct(); await focused('product-stockMinimum');
      await page.locator('#product-stockMinimum').fill('2');
      assert.equal(writes('/inventory/products').length,beforeProduct);
      await activeDialog().locator('summary').click();
      await page.locator('#product-barcode').fill('00123');
      await fixedFooter('product',width);
      control.product(400); await saveProduct();
      await activeDialog().getByRole('status').filter({hasText:'código interno'}).waitFor();
      await page.waitForFunction(() => document.activeElement?.hasAttribute('data-inventory-feedback'));
      assert.equal(await page.locator('#product-name').inputValue(),'Champú Prueba');
      assert.equal(await page.locator('#product-name').isDisabled(),false);
      control.product(503); await saveProduct();
      await activeDialog().getByText('Resultado por comprobar · Nuevo producto',{exact:true}).waitFor();
      assert.equal(await page.locator('#product-name').isDisabled(),true);
      assert.equal(await activeDialog().getByRole('button',{name:'Guardar producto',exact:true}).isDisabled(),true);
      assert.equal(writes('/inventory/products').length,beforeProduct+2);
      const durable = await page.evaluate(() => JSON.parse(localStorage.getItem('mateos-inventory-pending-v1:fixture-only-inventory')));
      assert.equal(durable.length,1); assert.match(durable[0].key,/^[a-f0-9-]{36}$/);
      assert.equal(JSON.parse(durable[0].body).referenceCost,'12000.50');
      assert.equal(JSON.parse(durable[0].body).barcode,'00123');
      control.product(0);
      await activeDialog().getByRole('button',{name:'Consultar resultado',exact:true}).click();
      await activeDialog().getByText('Producto registrado.',{exact:false}).waitFor();
      assert.equal(await activeDialog().getByRole('button',{name:'Guardar producto',exact:true}).count(),0);
      assert.equal(writes('/inventory/products').length,beforeProduct+2,'Recovery must not create a new product');
      assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('mateos-inventory-pending-v1:fixture-only-inventory')).length),0);
      await activeDialog().getByRole('button',{name:'Cerrar',exact:true}).last().click();
      console.log(`PASS: ${width}px product required fields, uses, COP format, integer stock, definitive failure and durable recovery without duplicate write; fixed footer.`);
    }
    // Slow save locks dismissal and fields; successful new item is one operation.
    await page.goto(url('inventory'),{waitUntil:'networkidle'});
    await page.getByRole('button',{name:'Nuevo producto',exact:true}).click();
    for (const [id,value] of Object.entries({name:'Producto Guardado',internalCode:'SAVE-1',category:'Aseo',presentation:'Frasco',referenceCost:'0'})) await page.locator('#product-'+id).fill(value);
    await page.locator('#product-use-grooming').check();
    let release; control.productGate(new Promise(resolve=>{release=resolve;})); releases.push(release);
    const before = writes('/inventory/products').length;
    await saveProduct(); await page.waitForFunction(()=>document.querySelector('#product-name')?.closest('fieldset[disabled]'));
    assert.equal(await page.locator('#product-name').isDisabled(),true);
    await page.keyboard.press('Escape'); assert.equal(await page.locator('#product-name').isVisible(),true);
    release(); control.productGate(null);
    await activeDialog().getByText('Producto registrado.',{exact:false}).waitFor();
    assert.equal(writes('/inventory/products').length,before+1);
    await activeDialog().getByRole('button',{name:'Cerrar',exact:true}).last().click();
    control.products(true); await page.reload({waitUntil:'networkidle'});
    await page.getByRole('button',{name:'Ver detalle',exact:true}).first().click();
    await page.getByRole('button',{name:'Editar',exact:true}).first().click();
    assert.equal(await page.locator('#product-presentation').isDisabled(),true);
    assert.equal(await page.locator('#product-lotPolicy').isDisabled(),true);
    await page.locator('#product-salePrice').fill('19000');
    await saveProduct();
    await activeDialog().getByRole('status').filter({hasText:'Operación guardada'}).waitFor();
    assert.equal(calls.filter(c=>c.method==='PATCH'&&c.path.endsWith('/inventory/products/product-fixture')).at(-1).body.expectedVersion,2);
    await activeDialog().getByRole('button',{name:'Cerrar',exact:true}).last().click();
    console.log('PASS: slow product save uses one operation, fields and Escape locked; editing preserves presentation/lot policy and metadata version.');
    await page.getByRole('button',{name:'Nuevo producto',exact:true}).click();
    for (const [id,value] of Object.entries({name:'Borrador conservado',internalCode:'FOREIGN-1',category:'Aseo',presentation:'Frasco',referenceCost:'0'})) await page.locator('#product-'+id).fill(value);
    await page.locator('#product-use-grooming').check();
    control.product(400); await saveProduct();
    await activeDialog().getByRole('status').filter({hasText:'código interno'}).waitFor();
    const foreign = {key:'11111111-1111-4111-8111-111111111111',kind:'create_product',path:'/api/dashboard/inventory/products',method:'POST',body:JSON.stringify({name:'Otra operación'}),label:'Otra pestaña',createdAt:Date.now()};
    control.foreignOperation(foreign);
    await page.evaluate(foreign=>{localStorage.setItem('mateos-inventory-pending-v1:fixture-only-inventory',JSON.stringify([foreign]));window.dispatchEvent(new Event('mateos-inventory-pending'));},foreign);
    await activeDialog().getByRole('button',{name:'Consultar resultado',exact:true}).click();
    await activeDialog().getByRole('status').filter({hasText:'Operación guardada'}).waitFor();
    assert.equal(await page.locator('#product-name').inputValue(),'Borrador conservado');
    assert.equal(await activeDialog().getByRole('button',{name:'Guardar producto',exact:true}).isEnabled(),true);
    assert.equal(await activeDialog().getByText('Producto registrado.',{exact:false}).count(),0);
    control.product(0); await cancel();
    console.log('PASS: recovering another tab operation does not mark the current product draft as saved.');
    assert.equal(errors.length,0,errors.join('\n'));
    assert(calls.filter(c=>c.method!=='GET').every(c=>c.tenant==='fixture-selected'));
    console.log('PASS: 33 form structure scenarios; fixture-only API writes, no real database changes or outgoing messages.');
  } finally { releases.forEach(release=>release()); control.productGate(null); await context.close(); }
};
