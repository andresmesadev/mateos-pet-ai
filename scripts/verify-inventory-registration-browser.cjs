const assert = require('node:assert/strict');
const path = require('node:path');

module.exports = async function verify({ page, prisma, base, tenantId, output, check }) {
  await prisma.tenant.update({ where: { id: tenantId }, data: { activeModules: ['veterinary', 'grooming', 'retail'] } });
  const name = 'Producto inicial de verificación';
  const dialog = () => page.getByRole('dialog').last();
  const footer = () => dialog().locator('[data-slot="dialog-footer"]');
  const response = suffix => page.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname.endsWith(suffix));
  const close = async () => { await footer().getByRole('button', { name: 'Cerrar', exact: true }).click(); await dialog().waitFor({ state: 'hidden' }); };
  async function layout(file) {
    const d = await dialog().boundingBox();
    const vp = page.viewportSize();
    assert(d.x >= 0 && d.x + d.width <= vp.width + 1);
    assert(d.y >= 0 && d.y + d.height <= vp.height + 1);
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    const action = await footer().boundingBox();
    assert(action.y + action.height <= vp.height + 1);
    await page.screenshot({ path: path.join(output, file) });
  }
  await page.setViewportSize({ width: 320, height: 720 });
  await page.goto(base + '/dashboard/inventory');
  await page.getByRole('button', { name: 'Nuevo producto', exact: true }).click();
  await page.locator('#product-name').fill(name);
  await page.locator('#product-internalCode').fill('INITIAL-BROWSER');
  await page.locator('#product-category').fill('Verificación');
  await page.locator('#product-presentation').fill('Frasco');
  await page.locator('#product-use-retail').check();
  await page.locator('#product-referenceCost').fill('500');
  await page.locator('#product-salePrice').fill('1000');
  await page.locator('#product-initialQuantity').fill('5');
  await page.locator('#product-lotPolicy').selectOption('lot_expiry');
  await footer().getByRole('button', { name: 'Guardar producto', exact: true }).click();
  await page.waitForFunction(() => document.activeElement?.id === 'product-initialLot');
  await page.locator('#product-initialLot').fill('INITIAL-LOT');
  await page.locator('#product-initialExpiry').fill('2030-12-01');
  await layout('46-inventory-initial-stock-mobile.png');
  const created = response('/inventory/products');
  await footer().getByRole('button', { name: 'Guardar producto', exact: true }).click();
  const creation = await created; assert.equal(creation.status(), 200);
  const product = (await creation.json()).product;
  await dialog().getByText('Producto registrado con 5 unidades iniciales.', { exact: false }).waitFor();
  await close();
  const read = () => prisma.inventoryProduct.findUniqueOrThrow({ where: { id: product.id }, include: { lots: true } });
  assert.equal((await read()).lots[0].balancePhysical, 5);
  check('Inventory UI creates product plus initial stock atomically, validates required lot and fits 320px');

  async function open() {
    await page.getByRole('button', { name, exact: true }).click();
    await dialog().getByRole('tab', { name: 'Movimientos', exact: true }).click();
  }
  await open();
  await dialog().getByRole('button', { name: 'Corregir cantidad y costo', exact: true }).click();
  await page.locator('#entry-correction-quantity').fill('7');
  await page.locator('#entry-correction-cost').fill('600');
  await footer().getByRole('button', { name: 'Guardar corrección', exact: true }).click();
  await page.waitForFunction(() => document.activeElement?.id === 'entry-correction-reason');
  await page.locator('#entry-correction-reason').fill('Fueron siete frascos a seiscientos pesos');
  await layout('47-inventory-entry-correction-mobile.png');
  const corrected = response('/corrections');
  await footer().getByRole('button', { name: 'Guardar corrección', exact: true }).click();
  assert.equal((await corrected).status(), 200);
  await dialog().getByText('Corrección guardada.', { exact: false }).waitFor();
  await close();
  assert.equal((await read()).lots[0].balancePhysical, 7);
  const movements = await prisma.inventoryMovement.findMany({ where: { productId: product.id, kind: 'entry' } });
  assert.deepEqual(movements.map(m => [m.quantity, Number(m.entryUnitCost)]).sort((a,b)=>a[0]-b[0]), [[5,500],[7,600]]);
  check('Inventory UI corrects quantity and cost with required reason, preserving the original entry');

  await page.setViewportSize({ width: 768, height: 900 });
  await open();
  assert.equal(await dialog().getByText('Entrada corregida; se conserva como antecedente.', { exact: true }).count(), 1);
  await dialog().getByRole('button', { name: 'Corregir cantidad y costo', exact: true }).click();
  await page.locator('#entry-correction-quantity').fill('0');
  await page.locator('#entry-correction-reason').fill('Alta de prueba equivocada');
  const canceled = response('/corrections');
  await footer().getByRole('button', { name: 'Guardar corrección', exact: true }).click();
  const canceledResponse = await canceled;
  assert.equal(canceledResponse.status(), 200, JSON.stringify(await canceledResponse.json()));
  await dialog().getByText('Corrección guardada.', { exact: false }).waitFor(); await close();
  assert.equal((await read()).lots[0].balancePhysical, 0);
  await page.getByLabel('Incluir desactivados', { exact: true }).check();
  await open();
  await dialog().getByRole('button', { name: 'Desactivar', exact: true }).click();
  await dialog().waitFor({ state: 'hidden' });
  await page.getByRole('button', { name, exact: true }).click();
  await dialog().getByRole('button', { name: 'Eliminar', exact: true }).click();
  await page.setViewportSize({ width: 320, height: 720 });
  await footer().getByRole('button', { name: 'Eliminar producto', exact: true }).click();
  await page.waitForFunction(() => document.activeElement?.id === 'product-removal-reason');
  await page.locator('#product-removal-reason').fill('Registro equivocado de verificación');
  await layout('48-inventory-remove-mobile.png');
  const removed = response('/removal');
  await footer().getByRole('button', { name: 'Eliminar producto', exact: true }).click();
  const removedResponse = await removed;
  assert.equal(removedResponse.status(), 200, JSON.stringify(await removedResponse.json()));
  await dialog().getByText('Producto eliminado del catálogo.', { exact: true }).waitFor(); await close();
  assert((await read()).removedAt);
  assert.equal(await prisma.inventoryOperation.count({ where: { tenantId, kind: 'remove_product', resultProductId: product.id } }), 1);
  await page.getByRole('button', { name, exact: true }).waitFor({ state: 'hidden' });
  check('Inventory UI cancels an unused receipt, deactivates then removes an erroneous product with audit and no catalog residue');
};
