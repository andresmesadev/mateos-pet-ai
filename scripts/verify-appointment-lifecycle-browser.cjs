const assert=require('node:assert/strict');
const {randomUUID}=require('node:crypto');
module.exports=async({prisma,base,page,context,output,check,tenantId})=>{
 const marker=randomUUID().slice(0,8);
 const user=await prisma.user.create({data:{tenantId,name:'Lifecycle owner '+marker,phone:'lc-'+marker}});
 const pet=await prisma.pet.create({data:{tenantId,ownerId:user.id,name:'Lifecycle pet '+marker,type:'dog',defaultGroomingPrice:50000}});
 let category=await prisma.serviceCategory.findFirst({where:{tenantId,name:'grooming'}});
 if(!category)category=await prisma.serviceCategory.create({data:{tenantId,name:'grooming'}});
 const service=await prisma.service.create({data:{tenantId,categoryId:category.id,name:'Lifecycle service '+marker,duration:20,basePrice:50000}});
 const appointment=await prisma.appointment.create({data:{tenantId,userId:user.id,petId:pet.id,petName:pet.name,petType:'dog',serviceId:service.id,serviceType:'grooming',availabilityBucket:'grooming',date:new Date('2099-01-05T16:00Z'),status:'in_progress',startedAt:new Date('2099-01-05T16:00Z')}});
 const duplicate=await context.request.post(base+'/api/proxy/dashboard/appointments',{data:{userId:user.id,petId:pet.id,serviceId:service.id,dateKey:'2099-01-05',hour:12}});
 assert.equal(duplicate.status(),409);assert.equal((await duplicate.json()).code,'DUPLICATE_PET_APPOINTMENT');
 check('same pet/service/day is rejected through the authenticated scheduling API');
 await page.goto(base+'/dashboard/calendar?date=2099-01-05');
 await page.getByRole('button',{name:`${pet.name}, propietario ${user.name}, servicio ${service.name}`,exact:true}).click();
 const dialog=page.getByRole('dialog').filter({has:page.getByRole('heading',{name:'Cita de '+pet.name,exact:true})});await dialog.waitFor();
 await dialog.getByRole('button',{name:'Eliminar cita',exact:true}).click();
 await dialog.getByLabel('Motivo de la eliminación',{exact:true}).fill('Cita duplicada de prueba aislada');
 await dialog.getByRole('button',{name:'Eliminar cita creada por error',exact:true}).click();
 await page.getByRole('alertdialog').getByRole('button',{name:'Cancelar',exact:true}).click();
 assert.equal(await prisma.appointment.count({where:{id:appointment.id}}),1);
 assert.equal(await prisma.appointmentRemoval.count({where:{appointmentId:appointment.id}}),0);
 await page.setViewportSize({width:390,height:720});
 await dialog.evaluate(async el=>{await Promise.all(el.getAnimations().map(a=>a.finished));await new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)));});
 await dialog.locator('[data-appointment-body]').evaluate(el=>{el.scrollTop=el.scrollHeight;});
 assert.equal(await dialog.getByLabel('Motivo de la eliminación').inputValue(),'Cita duplicada de prueba aislada');
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:require('node:path').join(output,'50-appointment-removal-mobile.png'),animations:'disabled'});
 await dialog.getByRole('button',{name:'Eliminar cita creada por error',exact:true}).click();
 await page.getByRole('alertdialog').getByRole('button',{name:'Eliminar esta cita',exact:true}).click();
 await dialog.waitFor({state:'hidden'});
 assert.equal(await prisma.appointment.count({where:{id:appointment.id}}),0);
 assert.equal(await prisma.appointmentRemoval.count({where:{appointmentId:appointment.id,tenantId}}),1);
 await page.reload();assert.equal(await page.getByRole('button',{name:`${pet.name}, propietario ${user.name}, servicio ${service.name}`,exact:true}).count(),0);
 check('calendar removes only after explicit reason/confirmation; cancel preserves it; mobile and reload preserve the result');
 await page.setViewportSize({width:1440,height:1000});
};
